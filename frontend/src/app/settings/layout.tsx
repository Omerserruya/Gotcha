"use client";

import { usePathname } from "next/navigation";
import Link from "next/link";
import { useI18n } from "@/context/I18nContext";
import { AppLayout } from "@/components/AppLayout";
import { useVoiceFlags } from "@/lib/use-voice-flags";
import clsx from "clsx";

interface SettingsNavItem {
  href: string;
  labelKey?: string;
  label?: string;
  icon: (props: { className?: string }) => React.ReactElement;
  exact?: boolean;
  voiceOnly?: boolean;
}

const settingsNav: SettingsNavItem[] = [
  { href: "/settings", labelKey: "settings.nav.general", icon: GeneralIcon, exact: true },
  { href: "/settings/agents", labelKey: "nav.agents", icon: AgentsIcon },
  { href: "/settings/departments", labelKey: "nav.departments", icon: DepartmentsIcon },
  { href: "/settings/channels", labelKey: "nav.channels", icon: ChannelsIcon },
  { href: "/settings/integrations", labelKey: "settings.nav.integrations", icon: IntegrationsIcon },
  { href: "/settings/usage", labelKey: "nav.usage", icon: UsageIcon },
  { href: "/settings/policy", labelKey: "settings.nav.policy", icon: PolicyIcon },
  { href: "/settings/intelligence", labelKey: "settings.nav.intelligence", icon: IntelligenceIcon },
  { href: "/settings/tools", labelKey: "settings.nav.tools", icon: ToolsIcon },
  { href: "/settings/voice-channels", labelKey: "settings.nav.voiceChannels", icon: VoiceChannelsIcon, voiceOnly: true },
  { href: "/settings/funnels", labelKey: "settings.nav.funnels", icon: FunnelIcon },
  { href: "/settings/permissions", labelKey: "settings.nav.permissions", icon: PermissionsIcon },
  { href: "/settings/notifications", labelKey: "notifications.title", icon: NotificationsIcon },
];

export default function SettingsLayout({ children }: { children: React.ReactNode }) {
  const { t } = useI18n();
  const pathname = usePathname();
  const flags = useVoiceFlags();

  const visibleNav = settingsNav.filter((item) => {
    if (item.voiceOnly) return flags.voiceCopilotEnabled;
    return true;
  });

  function labelFor(item: SettingsNavItem): string {
    return item.labelKey ? t(item.labelKey) : item.label ?? "";
  }

  return (
    <AppLayout>
      <div className="flex h-[calc(100vh-16px)] md:gap-2 md:p-2">
        {/* Settings sidebar - hidden on mobile, shown on md+ */}
        <aside className="hidden md:flex w-[220px] flex-col bg-white rounded-2xl shadow-subtle overflow-hidden shrink-0">
          <div className="px-4 py-3 bg-gray-50/50">
            <h2 className="text-sm font-semibold text-gray-900">{t("nav.settings")}</h2>
          </div>
          <nav className="flex-1 py-2 px-2 space-y-0.5 overflow-y-auto">
            {visibleNav.map((item) => {
              const isActive = item.exact
                ? pathname === item.href
                : pathname.startsWith(item.href);
              return (
                <Link
                  key={item.href}
                  href={item.href}
                  className={clsx(
                    "flex items-center gap-2.5 px-3 py-2 rounded-xl text-xs font-medium transition-all",
                    isActive
                      ? "bg-primary-50/70 text-primary-600"
                      : "text-gray-500 hover:text-gray-700 hover:bg-gray-50"
                  )}
                >
                  <item.icon className="w-4 h-4 shrink-0" />
                  {labelFor(item)}
                </Link>
              );
            })}
          </nav>
        </aside>

        {/* Main content */}
        <div className="flex-1 overflow-y-auto md:rounded-2xl md:bg-white md:shadow-subtle">
          {/* Mobile settings tabs */}
          <div className="md:hidden flex overflow-x-auto bg-white shadow-subtle px-2 py-2 gap-1 sticky top-0 z-10">
            {visibleNav.map((item) => {
              const isActive = item.exact
                ? pathname === item.href
                : pathname.startsWith(item.href);
              return (
                <Link
                  key={item.href}
                  href={item.href}
                  className={clsx(
                    "flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-[11px] font-medium whitespace-nowrap transition shrink-0",
                    isActive
                      ? "bg-primary-50 text-primary-600"
                      : "text-gray-400 hover:text-gray-600 hover:bg-gray-50"
                  )}
                >
                  {labelFor(item)}
                </Link>
              );
            })}
          </div>
          {children}
        </div>
      </div>
    </AppLayout>
  );
}


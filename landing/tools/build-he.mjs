/**
 * Turns the design's he.js (a `window.GOTCHA_HE = {...}` script) into a module.
 *
 * Kept as JavaScript, verbatim: the dictionary has duplicate keys, which is
 * legal JS (the last wins, and that is what the design renders) but a
 * TypeScript error. Rewriting it to satisfy the compiler would be editing the
 * copy, so the file stays untyped instead.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DESIGN = path.join(ROOT, 'design');

let src = fs.readFileSync(path.join(DESIGN, 'he.js'), 'utf8');

const GLOBAL = 'window.GOTCHA_HE = {';
if (!src.includes(GLOBAL)) throw new Error('GOTCHA_HE assignment not found');
src = src.replace(GLOBAL, 'export const HE_DICT = {');

/* The older pages' bar and drawer now carry the v8 offer wording (build-logic.mjs,
   OLD_OFFER_SWAPS). Their Hebrew is the v8 dictionary's own, appended here for
   exactly those strings - none of them is already in this dictionary with a
   different translation (asserted), so nothing else on the older pages moves. */
import vm from 'node:vm';
const V8_HE = (() => { const c = { window: {} }; vm.runInNewContext(fs.readFileSync(path.join(DESIGN, 'home-v8/he.js'), 'utf8'), c); return c.window.GOTCHA_HE; })();
const OLD_HE = (() => { const c = { window: {} }; vm.runInNewContext(fs.readFileSync(path.join(DESIGN, 'he.js'), 'utf8'), c); return c.window.GOTCHA_HE; })();
const OFFER_KEYS = [
  'First month free, no commitment! For the first 50 businesses.', 'First month free', 'First month free!', 'Your first month free!', 'Free',
  'for the first month, no commitment', '1,000 credits for the month', 'The free month starts once you are connected',
];
const TERMS_V8 = 'Offer ends 31 October 2026 or when 50 businesses have joined, whichever comes first. After the first month you continue on the plan and usage you choose, with no commitment. Regular pricing starts at $39 a month, excluding 18% VAT.';
const extra = {};
for (const k of OFFER_KEYS) {
  if (V8_HE[k] === undefined) throw new Error(`v8 he.js has no ${k}`);
  if (OLD_HE[k] !== undefined && OLD_HE[k] !== V8_HE[k]) throw new Error(`old he.js already translates ${k} differently`);
  extra[k] = V8_HE[k];
}
if (V8_HE[TERMS_V8] === undefined || !V8_HE[TERMS_V8].includes('ב-31 באוקטובר 2026')) throw new Error('v8 he.js terms changed');
extra[TERMS_V8.replace('31 October 2026', '31 December 2026')] = V8_HE[TERMS_V8].replace('ב-31 באוקטובר 2026', 'ב-31 בדצמבר 2026');
const lastBrace = src.lastIndexOf('};');
if (lastBrace < 0) throw new Error('he.js: no closing brace');
src = src.slice(0, lastBrace) + '  // v8 offer wording on the older pages (tools/build-he.mjs)\n' +
  Object.entries(extra).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n') + '\n' + src.slice(lastBrace);

const out = path.join(ROOT, 'src/generated/he.js');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, '/* GENERATED by tools/build-he.mjs from design/he.js - do not edit. */\n' + src);

const keys = [...src.matchAll(/(?:^|[{,]\s*)(['"])((?:\\.|(?!\1).)*)\1\s*:/gs)].map((m) => m[2]);
const seen = new Set();
const dupes = keys.filter((k) => (seen.has(k) ? true : (seen.add(k), false)));

console.log('he.js:', keys.length, 'entries,', seen.size, 'distinct');
if (dupes.length) {
  console.log(`  ${dupes.length} duplicate key(s) - later values win, earlier ones are dead:`);
  [...new Set(dupes)].slice(0, 8).forEach((k) => console.log('   ', JSON.stringify(k.slice(0, 70))));
}

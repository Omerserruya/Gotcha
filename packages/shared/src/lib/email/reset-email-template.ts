/**
 * The password-reset email, as an Authentik (Django) template generated from
 * renderBrandEmail() (2026-10-22).
 *
 * Authentik sends this email itself (the recovery flow's email stage), so it
 * cannot call renderBrandEmail per send. Instead the brand renderer is run here
 * once per language with Django placeholders as its values, and the output is
 * committed as scripts/authentik/templates/gotcha_password_reset.html. A test
 * regenerates it and fails on any difference, so it cannot drift from the look
 * of every other GOTCHA email.
 *
 * Language: the email stage renders inside translation.override(user locale),
 * the user's saved locale or else the request's Accept-Language, so the
 * template picks Hebrew (RTL) or English with {% get_current_language %}.
 *
 * Context the stage provides: url, user, expires. `expires|timeuntil` is
 * localized by Django under that override, and follows the stage's token
 * expiry instead of a number written here.
 */
import { renderBrandEmail } from "./brand-email";

/** The app origin the logo and the legal links point at (dev and prod share the file). */
export const RESET_EMAIL_APP_URL = "https://app.gotcha.co.il";

const NAME = "{{ user.name|default:user.username }}";
const URL = "{{ url }}";
const EXPIRES = "{{ expires|timeuntil }}";

function render(locale: "en" | "he"): string {
  const he = locale === "he";
  return renderBrandEmail({
    locale,
    title: he ? "איפוס הסיסמה ל-GOTCHA" : "Reset your GOTCHA password",
    preheader: he ? "בחרו סיסמה חדשה לחשבון GOTCHA שלכם." : "Choose a new password for your GOTCHA account.",
    eyebrow: he ? "איפוס סיסמה" : "Password reset",
    icon: "&#128273;",
    headline: he ? "איפוס הסיסמה" : "Reset your password",
    subhead: he
      ? `${NAME}, קיבלנו בקשה לאפס את הסיסמה לחשבון GOTCHA שלכם. לחצו על הכפתור כדי לבחור סיסמה חדשה.`
      : `${NAME}, we received a request to reset the password for your GOTCHA account. Use the button below to choose a new one.`,
    cta: { label: he ? "בחירת סיסמה חדשה" : "Choose a new password", url: URL },
    fallbackUrl: URL,
    expiryNote: he ? `הקישור תקף עוד ${EXPIRES} ולשימוש אחד.` : `This link expires in ${EXPIRES} and works once.`,
    footerNote: he
      ? "קיבלתם את המייל הזה כי מישהו ביקש לאפס את הסיסמה לחשבון הזה. אם זה לא הייתם אתם, אפשר להתעלם ממנו: הסיסמה לא תשתנה."
      : "You're receiving this because someone asked to reset the password for this account. If that wasn't you, ignore this email: your password won't change.",
  });
}

/** The whole template file. Pure apart from pinning the app origin while rendering. */
export function buildResetEmailTemplate(): string {
  const prev = process.env.FRONTEND_URL;
  process.env.FRONTEND_URL = RESET_EMAIL_APP_URL;
  try {
    const en = render("en");
    const he = render("he");
    return [
      "{% load i18n %}{% get_current_language as LANGUAGE_CODE %}",
      "{# GENERATED by scripts/authentik/build-reset-email.ts from renderBrandEmail(); do not edit by hand. #}",
      "{# Authentik's recovery email stage. Context: url, user, expires. Hebrew when the user's language is Hebrew. #}",
      '{% if LANGUAGE_CODE|slice:":2" == "he" %}',
      he,
      "{% else %}",
      en,
      "{% endif %}",
      "",
    ].join("\n");
  } finally {
    if (prev === undefined) delete process.env.FRONTEND_URL;
    else process.env.FRONTEND_URL = prev;
  }
}

#!/usr/bin/env node
/**
 * Fetches the product's typefaces into the repo, once, on a machine with a
 * network, and writes the `@font-face` rules that serve them.
 *
 *   node scripts/fetch-fonts.mjs
 *
 * ── WHY THE FILES LIVE IN THE REPO (2026-10-21) ──
 * `next/font/google` downloads the fonts DURING `next build`. The production
 * image is arm64, built under QEMU from an amd64 host, and QEMU's networking
 * cannot reach fonts.gstatic.com: the build hangs about 30 minutes and fails
 * (gateway/Dockerfile.prod says the same of the legacy app). With the files
 * here, a build fetches nothing.
 *
 * The rules are Google's own, unchanged but for the URL: the same files, one
 * per subset, with the same `unicode-range`, which is what `next/font/google`
 * emitted. Only the subsets this product uses are kept.
 *
 * Re-run it to change a family or a subset, then commit both the files and
 * the CSS. `fonts.test.ts` checks that every rule names a file that exists.
 */
import { spawnSync } from 'node:child_process';
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src/design-system/fonts');

// A current Chrome gets woff2 split by unicode-range - the same answer next/font received.
const UA =
  'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36';

/** family query, the slug for file names, the subsets kept (as Google labels them). */
const FAMILIES = [
  ['Archivo:wght@100..900', 'archivo', ['latin']],
  ['Heebo:wght@100..900', 'heebo', ['hebrew', 'latin']],
  ['Instrument+Serif:ital@0;1', 'instrument-serif', ['latin']],
  ['Frank+Ruhl+Libre:wght@300..900', 'frank-ruhl-libre', ['hebrew', 'latin']],
  ['IBM+Plex+Mono:wght@400;500', 'ibm-plex-mono', ['latin']],
];

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

const header = `/*
 * GENERATED by scripts/fetch-fonts.mjs - do not edit by hand. Google's own
 * @font-face rules for the subsets this product uses, served from this repo so
 * that a build fetches nothing (see the script).
 */
`;
const rules = [];
for (const [query, slug, keep] of FAMILIES) {
  const res = await fetch(`https://fonts.googleapis.com/css2?family=${query}&display=swap`, {
    headers: { 'user-agent': UA },
  });
  if (!res.ok) throw new Error(`${query}: HTTP ${res.status}`);
  const css = await res.text();
  // Each block: /* subset */ @font-face { ... }
  for (const [, subset, body] of css.matchAll(/\/\* ([a-z-]+) \*\/\s*@font-face \{([^}]*)\}/g)) {
    if (!keep.includes(subset)) continue;
    const url = /src: url\(([^)]+)\)/.exec(body)?.[1];
    const style = /font-style: (\w+)/.exec(body)?.[1] ?? 'normal';
    const weight = /font-weight: ([\d ]+);/.exec(body)?.[1]?.trim() ?? '400';
    if (!url) throw new Error(`${query} ${subset}: no url`);
    const file = `${slug}-${subset}-${weight.replace(' ', '-')}-${style}.woff2`;
    const font = await fetch(url, { headers: { 'user-agent': UA } });
    if (!font.ok) throw new Error(`${url}: HTTP ${font.status}`);
    writeFileSync(join(OUT, file), Buffer.from(await font.arrayBuffer()));
    // Quotes only where a name needs them (stylelint font-family-name-quotes).
    const named = body.replace(/font-family: '([^' ]+)'/, 'font-family: $1');
    rules.push(
      `/* ${slug}, ${subset} */\n@font-face {${named.replace(/src: url\([^)]+\)/, `src: url('./${file}')`)}}\n`,
    );
  }
}
writeFileSync(join(OUT, 'fonts.css'), header + '\n' + rules.join('\n'));
// In the repo's style, so format:check passes on a fresh run.
spawnSync('npx', ['prettier', '--write', join(OUT, 'fonts.css')], { stdio: 'inherit' });
console.log(`${rules.length} faces written to ${OUT}`);
